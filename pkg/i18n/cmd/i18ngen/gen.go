// File is one output file, its path relative to the repo root.
type File struct {
	Path string
	Data []byte
}

const (
	serverOut = "pkg/i18n/servertext"
	screenOut = "screen/i18n/gen"
)

// Generate checks both areas' catalogs and returns every file made from them.
func Generate(root fs.FS) ([]File, error) {
	var files []File
	server, err := load(root, "server")
	if err != nil {
		return nil, err
	}
	for _, l := range i18n.Catalogued {
		name := path.Join("i18n", "server", string(l)+".json")
		data, err := fs.ReadFile(root, name)
		if err != nil {
			return nil, err
		}
		files = append(files, File{Path: path.Join(serverOut, "server", string(l)+".json"), Data: data})
	}
	goText, err := goTexts(server)
	if err != nil {
		return nil, err
	}
	files = append(files, File{Path: path.Join(serverOut, "text_gen.go"), Data: goText})

	screen, err := load(root, "screen")
	if err != nil {
		return nil, err
	}
	header, source, err := cppKeys(screen)
	if err != nil {
		return nil, err
	}
	files = append(files, File{Path: path.Join(screenOut, "keys.h"), Data: header},
		File{Path: path.Join(screenOut, "catalog.cpp"), Data: source})
	return files, nil
}

func load(root fs.FS, area string) (*i18n.Catalog, error) {
	sub, err := fs.Sub(root, "i18n")
	if err != nil {
		return nil, err
	}
	c, err := i18n.Load(sub, area)
	if err != nil {
		return nil, err
	}
	if errs := c.Check(); len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	return c, nil
}

// camel makes player.osd.voiceover into PlayerOsdVoiceover
func camel(key string) string {
	var b strings.Builder
	up := true
	for _, r := range key {
		if r == '.' || r == '_' {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

type entry struct {
	key, ident string
	args       []i18n.Arg
}

func entries(c *i18n.Catalog) ([]entry, error) {
	var out []entry
	idents := map[string]string{}
	for _, k := range c.Keys() {
		id := camel(k)
		if prev, ok := idents[id]; ok {
			return nil, fmt.Errorf("i18ngen: %s and %s both make %s", prev, k, id)
		}
		idents[id] = k
		src, _ := c.Source(i18n.En, k)
		m, err := i18n.Parse(src)
		if err != nil {
			return nil, err
		}
		args, err := m.ArgList()
		if err != nil {
			return nil, err
		}
		out = append(out, entry{key: k, ident: id, args: args})
	}
	return out, nil
}

var goKeywords = map[string]bool{"break": true, "case": true, "chan": true, "const": true, "continue": true,
	"default": true, "defer": true, "else": true, "fallthrough": true, "for": true, "func": true, "go": true,
	"goto": true, "if": true, "import": true, "interface": true, "map": true, "package": true, "range": true,
	"return": true, "select": true, "struct": true, "switch": true, "type": true, "var": true}

func goParam(name string) string {
	if goKeywords[name] {
		return name + "_"
	}
	return name
}

func goTexts(c *i18n.Catalog) ([]byte, error) {
	es, err := entries(c)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by pkg/i18n/cmd/i18ngen from i18n/server; DO NOT EDIT.\n\npackage servertext\n\n")
	b.WriteString("import \"git.shino.boo/devilreef/cadence/pkg/i18n\"\n\n")
	for _, e := range es {
		src, _ := c.Source(i18n.En, e.key)
		fmt.Fprintf(&b, "// %s is %s: %q\n", e.ident, e.key, src)
		var params, args []string
		for _, a := range e.args {
			t := "string"
			if a.Type == i18n.Number {
				t = "int64"
			}
			params = append(params, goParam(a.Name)+" "+t)
			args = append(args, fmt.Sprintf("%q: %s", a.Name, goParam(a.Name)))
		}
		argMap := "nil"
		if len(args) > 0 {
			argMap = "i18n.Args{" + strings.Join(args, ", ") + "}"
		}
		fmt.Fprintf(&b, "func %s(%s) i18n.Text {\n\treturn i18n.Text{Key: %q, Args: %s}\n}\n\n", e.ident,
			strings.Join(params, ", "), e.key, argMap)
	}
	return format.Source(b.Bytes())
}

