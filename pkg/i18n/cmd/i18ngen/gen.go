func cppField(name string) string {
	if cppKeywords[name] {
		return name + "_"
	}
	return name
}

// cppString is a c++ literal of s: ascii printable as is, every other byte as a three-digit octal escape (a hex
// escape would swallow the hex digits after it)
func cppString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '?':
			// no trigraphs
			b.WriteString(`\?`)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// comment is a message on one comment line
func comment(s string) string {
	return strings.NewReplacer("\n", `\n`, "*/", "* /", `\`, "(backslash)").Replace(s)
}

func cppKeys(c *i18n.Catalog) ([]byte, []byte, error) {
	es, err := entries(c)
	if err != nil {
		return nil, nil, err
	}
	var h bytes.Buffer
	h.WriteString(`// generated by pkg/i18n/cmd/i18ngen from i18n/screen; do not edit (make i18n)
#pragma once

#include "i18n/value.h"

#include <array>
#include <cstddef>
#include <string_view>

// one type per key, constructed from the key's arguments in the order they appear in en's message: a key no
// catalog has, a missing argument or one of the wrong type fails the build
namespace cadence::i18n::keys {

`)
	fmt.Fprintf(&h, "inline constexpr std::size_t kCount = %d;\n\n", len(es))
	for i, e := range es {
		src, _ := c.Source(i18n.En, e.key)
		fmt.Fprintf(&h, "// %s\nstruct %s {\n", comment(src), e.ident)
		fmt.Fprintf(&h, "  static constexpr std::size_t kIndex = %d;\n", i)
		fmt.Fprintf(&h, "  static constexpr std::string_view kId = %s;\n", cppString(e.key))
		if len(e.args) > 0 {
			var params, inits, items []string
			for _, a := range e.args {
				t := "std::string_view"
				if a.Type == i18n.Number {
					t = "Num"
				}
				f := cppField(a.Name)
				params = append(params, t+" "+f+"_arg")
				inits = append(inits, f+"("+f+"_arg)")
				items = append(items, fmt.Sprintf("Arg{%s, Value(%s)}", cppString(a.Name), f))
			}
			explicit := ""
			if len(e.args) == 1 {
				explicit = "explicit "
			}
			fmt.Fprintf(&h, "  %s%s(%s) : %s {}\n", explicit, e.ident, strings.Join(params, ", "),
				strings.Join(inits, ", "))
			for _, a := range e.args {
				t := "std::string_view"
				if a.Type == i18n.Number {
					t = "Num"
				}
				fmt.Fprintf(&h, "  %s %s;\n", t, cppField(a.Name))
			}
			fmt.Fprintf(&h, "  [[nodiscard]] std::array<Arg, %d> args() const { return {%s}; }\n", len(e.args),
				strings.Join(items, ", "))
		} else {
			h.WriteString("  [[nodiscard]] static std::array<Arg, 0> args() { return {}; }\n")
		}
		h.WriteString("};\n\n")
	}
	h.WriteString("}  // namespace cadence::i18n::keys\n")

	var s bytes.Buffer
	s.WriteString(`// generated by pkg/i18n/cmd/i18ngen from i18n/screen; do not edit (make i18n)
#include "i18n/catalog.h"
#include "i18n/gen/keys.h"

namespace cadence::i18n {
namespace {

// sorted by key; an entry's place is its key type's kIndex
constexpr CatalogEntry kEntries[] = {
`)
	for _, e := range es {
		en, _ := c.Source(i18n.En, e.key)
		ru, _ := c.Source(i18n.Ru, e.key)
		fmt.Fprintf(&s, "    {%s,\n     %s,\n     %s},\n", cppString(e.key), cppString(en), cppString(ru))
	}
	s.WriteString(`};

static_assert(std::size(kEntries) == keys::kCount);

}  // namespace

std::span<const CatalogEntry> builtin_entries() { return kEntries; }

}  // namespace cadence::i18n
`)
	return h.Bytes(), s.Bytes(), nil
}
