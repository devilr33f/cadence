// Messages formats a message of the screens' catalog in a language (bcp 47,
// "ru", "en"). Stream P's pkg/i18n is meant to satisfy it; until then
// Builtin serves the keys this server sends. args fill {name} placeholders.
type Messages interface {
	Format(lang, key string, args map[string]string) string
}

// Builtin is the server's own catalog: Russian and English, English for any
// other language, the key itself for a key it lacks.
var Builtin Messages = builtin{}

type builtin struct{}

func (builtin) Format(lang, key string, args map[string]string) string {
	table := builtinEN
	if base, _, _ := strings.Cut(strings.ToLower(lang), "-"); base == "ru" {
		table = builtinRU
	}
	s, ok := table[key]
	if !ok {
		if s, ok = builtinEN[key]; !ok {
			return key
		}
	}
	for k, v := range args {
		s = strings.ReplaceAll(s, "{"+k+"}", v)
	}
	return s
}

