// rotate is a yt-dlp stand-in body that writes the jar back as yt-dlp does, its own header first, with SID renewed
// to the value in the file rotated names (or kept while there is none)
func rotate(rotated string) string {
	return `prev=; for a in "$@"; do if [ "$prev" = --cookies ]; then jar=$a; fi; prev=$a; done
if [ -f ` + rotated + ` ]; then v=$(cat ` + rotated + `); sed "s/\tSID\t[^\t]*$/\tSID\t$v/" "$jar" > "$jar.new"; else cp "$jar" "$jar.new"; fi
{ echo '# Netscape HTTP Cookie File'; echo '# This file is generated by yt-dlp.  Do not edit.'; grep -v '^# Netscape' "$jar.new"; } > "$jar"
echo 10; echo '` + streamURL + `'`
}

type saves struct {
	mu  sync.Mutex
	got []string
}

func (s *saves) save(_ context.Context, key, value string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.got = append(s.got, key+"="+value)
	return nil
}

func (s *saves) all() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.got...)
}

// the jar yt-dlp writes back is the next run's and is saved once a cookie changed; a run that renews nothing (only
// the header and expiries yt-dlp rewrites) saves nothing
func TestRenewedCookiesAreKeptAndSaved(t *testing.T) {
	rotated := filepath.Join(t.TempDir(), "rotated")
	bin, dir := fakeBin(t, rotate(rotated))
	cookies, _ := ytdlp.Cookies(cookieTxt)
	var log bytes.Buffer
	s := &saves{}
	p := ytdlp.New(ytdlp.Config{Bin: bin, Cookies: cookies, Save: s.save, TempDir: t.TempDir(), Log: logger(&log)})

	if _, err := p.Resolve(context.Background(), "5qZQEq_C3vc"); err != nil {
		t.Fatal(err)
	}
	time.Sleep(50 * time.Millisecond)
	if len(s.all()) != 0 {
		t.Fatalf("saved an unchanged jar: %v", s.all())
	}

	if err := os.WriteFile(rotated, []byte("ROTATED-1"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := p.Resolve(context.Background(), "5qZQEq_C3vc"); err != nil {
		t.Fatal(err)
	}
	waitFor(t, func() bool { return len(s.all()) == 1 })
	if got := s.all()[0]; !strings.HasPrefix(got, "cookies=") || !strings.Contains(got, "\tSID\tROTATED-1") || !strings.Contains(got, "\tHSID\tOTHER") {
		t.Fatalf("saved %q", got)
	}
	// the next run starts from the renewed jar
	if _, err := p.Resolve(context.Background(), "5qZQEq_C3vc"); err != nil {
		t.Fatal(err)
	}
	given, _ := os.ReadFile(filepath.Join(dir, "cookies"))
	if !strings.Contains(string(given), "\tSID\tROTATED-1") {
		t.Fatalf("next run got %q", given)
	}
	if strings.Contains(log.String(), "ROTATED") || strings.Contains(log.String(), "COOKIE-SECRET") ||
		!strings.Contains(log.String(), "msg=ytdlp_cookies_renewed") || !strings.Contains(log.String(), "msg=ytdlp_cookies_saved") {
		t.Fatalf("log %s", log.String())
	}
}

// runs with cookies take turns: two at once would start from one jar, and the later write-back would undo the
// earlier one's rotation
func TestRunsWithCookiesTakeTurns(t *testing.T) {
	// each run marks itself in dir while it runs and records how many marks it saw
	dir := t.TempDir()
	bin, _ := fakeBin(t, `touch `+dir+`/$$; ls `+dir+` | wc -l >> `+dir+`.seen; sleep 0.3; rm `+dir+`/$$; echo 10; echo '`+streamURL+`'`)
	cookies, _ := ytdlp.Cookies(cookieTxt)
	p := ytdlp.New(ytdlp.Config{Bin: bin, Cookies: cookies, TempDir: t.TempDir()})
	var wg sync.WaitGroup
	for range 3 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if _, err := p.Resolve(context.Background(), "5qZQEq_C3vc"); err != nil {
				t.Error(err)
			}
		}()
	}
	wg.Wait()
	b, _ := os.ReadFile(dir + ".seen")
	if seen := strings.Fields(string(b)); len(seen) != 3 || seen[0] != "1" || seen[1] != "1" || seen[2] != "1" {
		t.Fatalf("runs overlapped: %q", b)
	}
}

func waitFor(t *testing.T, cond func() bool) {
	t.Helper()
	deadline := time.Now().Add(3 * time.Second)
	for !cond() {
		if time.Now().After(deadline) {
			t.Fatal("never happened")
		}
		time.Sleep(5 * time.Millisecond)
	}
}
